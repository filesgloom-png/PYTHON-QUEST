    private fun formatNoteCharacterCount(count: Int): String {
        val lastTwoDigits = count % 100
        val noun = when {
            lastTwoDigits in 11..14 -> "символов"
            count % 10 == 1 -> "символ"
            count % 10 in 2..4 -> "символа"
            else -> "символов"
        }
        return "$count $noun"
    }

